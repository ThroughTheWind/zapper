// Builds site/icons.svg, a sprite of the Material Symbols Rounded (filled, weight 500) icons that
// site/index.html uses, so the page needs no icon font and makes no third-party request.
//
//   node site/tools/icons.mjs --from <dir>   rebuild the sprite; <dir> is the unpacked
//                                            @material-symbols/svg-500 package (npm pack it)
//   node site/tools/icons.mjs --check        fail if index.html uses an icon the sprite lacks
//
// The icon list is read from index.html (every `icons.svg#name`), so it is never typed twice.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const site = join(dirname(fileURLToPath(import.meta.url)), "..");
const html = readFileSync(join(site, "index.html"), "utf8");
const used = [...new Set([...html.matchAll(/icons\.svg#([a-z0-9_]+)/g)].map((m) => m[1]))].sort();

const args = process.argv.slice(2);
if (args.includes("--check")) {
  let sprite = "";
  try {
    sprite = readFileSync(join(site, "icons.svg"), "utf8");
  } catch {
    // Missing sprite: every icon is missing.
  }
  const missing = used.filter((name) => !sprite.includes(`id="${name}"`));
  if (missing.length) {
    console.error(`site/icons.svg lacks: ${missing.join(", ")}. Rebuild it with --from.`);
    process.exit(1);
  }
  console.log(`site/icons.svg has all ${used.length} icons index.html uses.`);
} else {
  const from = args[args.indexOf("--from") + 1];
  if (!args.includes("--from") || !from) {
    console.error("Usage: node site/tools/icons.mjs --from <unpacked @material-symbols/svg-500 package> | --check");
    process.exit(2);
  }
  const symbols = used.map((name) => {
    const svg = readFileSync(join(from, "rounded", `${name}-fill.svg`), "utf8");
    const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
    const body = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
    return `<symbol id="${name}" viewBox="${viewBox}">${body}</symbol>`;
  });
  const sprite = `<svg xmlns="http://www.w3.org/2000/svg">
<!-- Material Symbols Rounded, filled, weight 500 (Apache-2.0, Google). Generated by site/tools/icons.mjs. -->
${symbols.join("\n")}
</svg>
`;
  writeFileSync(join(site, "icons.svg"), sprite);
  console.log(`Wrote ${used.length} icons to site/icons.svg`);
}
