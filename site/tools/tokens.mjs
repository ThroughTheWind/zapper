// Generates site/tokens.css from the landing design system's tokens (docs/design/web/tokens.json).
//
//   node site/tools/tokens.mjs           write site/tokens.css
//   node site/tools/tokens.mjs --check   fail if site/tokens.css is out of date
//
// Edit the tokens, never tokens.css: the Pages workflow runs --check and refuses a hand edit.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const source = join(root, "docs", "design", "web", "tokens.json");
const target = join(root, "site", "tokens.css");

const tokens = JSON.parse(readFileSync(source, "utf8"));

// A value such as "{surface-container-highest}" is an alias of another token.
const value = (v) => (typeof v === "string" ? v.replace(/^\{(.+)\}$/, "var(--$1)") : v);

const themed = { dark: [], light: [] };
const fixed = [];
for (const t of tokens.color.tokens) {
  if (t.value !== null && typeof t.value === "object") {
    themed.dark.push(`  --${t.name}: ${value(t.value.dark)};`);
    themed.light.push(`  --${t.name}: ${value(t.value.light)};`);
  } else {
    fixed.push(`  --${t.name}: ${value(t.value)};`);
  }
}
for (const group of ["spacing", "radius", "shadow", "size", "opacity"]) {
  for (const t of tokens[group].tokens) fixed.push(`  --${t.name}: ${value(t.value)};`);
}
for (const [name, family] of Object.entries(tokens.type.families)) fixed.push(`  --font-${name}: ${family};`);

const css = `/* Generated by site/tools/tokens.mjs from docs/design/web/tokens.json. Do not edit. */
:root {
  color-scheme: dark light;
${fixed.join("\n")}
${themed.dark.join("\n")}
}
@media (prefers-color-scheme: light) {
  :root {
${themed.light.map((l) => "  " + l).join("\n")}
  }
}
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // Missing counts as out of date.
  }
  if (current !== css) {
    console.error("site/tokens.css is out of date: run `node site/tools/tokens.mjs` and commit the result.");
    process.exit(1);
  }
  console.log("site/tokens.css matches docs/design/web/tokens.json.");
} else {
  writeFileSync(target, css);
  console.log(`Wrote ${target}`);
}
